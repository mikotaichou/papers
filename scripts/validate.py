ARXIV_RE = re.compile(
    r"^https?://arxiv\.org/(?:abs|pdf)/(\d{4}\.\d{4,5})(?:v\d+)?(?:\.pdf)?/?$"
)
ENTRY_RE = re.compile(r"^(\d+)\.\s+((?:📄|🔒)\s+)?\[(.+?)\]\((\S+?)\)(.*)$")
BULLET_RE = re.compile(r"^- ((?:📄|🔒)\s+)?\[(.+?)\]\((\S+?)\)(.*)$")
AREA_LINK_RE = re.compile(r"\s+—\s+\[([^\]]+)\]\((learning/[a-z-]+\.md)\)\s*$")
MD_LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")


class Finding:
    def __init__(self, severity, file, line, check, message):
        self.severity = severity
        self.file = file
        self.line = line
        self.check = check
        self.message = message

    def render(self):
        return f"{self.severity} {self.file}:{self.line} [{self.check}] {self.message}"


class Repo:
    """Parsed model of the repo, rebuilt from disk on each construction."""

    def __init__(self):
        self.findings = []
        self.topic_files = sorted(
            p for p in LEARNING.glob("*.md") if p.name != "glossary.md"
        )
        self.topics = {}  # stem -> list of sections
        for path in self.topic_files:
            self.topics[path.stem] = self._parse_topic(path)
        self.bydate = self._parse_bydate()
        self.glossary_anchors, self.glossary_terms = self._parse_glossary()

    # -- helpers ----------------------------------------------------------
    def error(self, file, line, check, message):
        self.findings.append(Finding("ERROR", file, line, check, message))

    def warn(self, file, line, check, message):
        self.findings.append(Finding("WARN ", file, line, check, message))

    # -- parsing ----------------------------------------------------------
    def _parse_topic(self, path):
        sections = []
        current = None
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines, 1):
            if line.startswith("## "):
                current = {"name": line[3:].strip(), "line": i, "entries": []}
                sections.append(current)
            elif current is not None:
                m = ENTRY_RE.match(line)
                if m:
                    current["entries"].append(
                        {
                            "num": int(m.group(1)),
                            "line": i,
                            "emoji": (m.group(2) or "").strip(),
                            "title": m.group(3),
                            "url": m.group(4),
                            "rest": m.group(5),
                            "cont": [],
                        }
                    )
                elif re.match(r"^\d+\.\s", line):
                    self.error(
                        rel(path), i, "entry-format",
                        f'numbered item is not "[Title](url)" form: "{line[:60]}..." '
                        "-> use `N. [Title](url) (Authors, Year)` or an unnumbered bullet",
                    )
                elif current["entries"] and re.match(r"^\s+-\s", line):
                    current["entries"][-1]["cont"].append((i, line))
        return sections

    def _parse_bydate(self):
        model = {"years": [], "bullets": [], "footer": {}, "lines": []}
        lines = BYDATE.read_text(encoding="utf-8").splitlines()
        model["lines"] = lines
        year = None
        month = None
        for i, line in enumerate(lines, 1):
            if line.startswith("## ") and not line.startswith("###"):
                head = line[3:].strip()
                m = re.match(r"^(\d{4})$", head)
                year = {"raw": head, "line": i, "year": int(m.group(1)) if m else None,
                        "months": []}
                month = None
                model["years"].append(year)
                if not m:
                    self.error(
                        "by-date.md", i, "structure",
                        f'year heading "## {head}" not in "## YYYY" form '
                        "-> split/normalize into single-year sections",
                    )
            elif line.startswith("### "):
                head = line[4:].strip()
                m = re.match(r"^(\d{4})\.(\d{2})$", head)
                month = {"raw": head, "line": i,
                         "year": int(m.group(1)) if m else None,
                         "month": int(m.group(2)) if m else None}
                if year is not None:
                    year["months"].append(month)
                if not m:
                    self.error(
                        "by-date.md", i, "structure",
                        f'month heading "### {head}" not in "### YYYY.MM" form '
                        "-> normalize (e.g. venue/era labels become YYYY.MM or plain year section)",
                    )
                elif year is not None and year["year"] is not None and m and int(m.group(1)) != year["year"]:
                    self.error(
                        "by-date.md", i, "structure",
                        f'month "### {head}" sits inside "## {year["raw"]}" '
                        f"-> move it under ## {m.group(1)}",
                    )
            else:
                b = BULLET_RE.match(line)
                if b:
                    rest = b.group(4)
                    area = AREA_LINK_RE.search(rest)
                    if area:
                        rest_wo_area = rest[: area.start()]
                    else:
                        rest_wo_area = rest
                    model["bullets"].append(
                        {
                            "line": i,
                            "emoji": (b.group(1) or "").strip(),
                            "title": b.group(2),
                            "url": b.group(3),
                            "rest": rest_wo_area,
                            "area_label": area.group(1) if area else None,
                            "area_target": area.group(2) if area else None,
                            "year": year["year"] if year else None,
                            "month": month["month"] if month else None,
                        }
                    )
                m = re.match(r"^\*\*Total Papers in Learning Path\*\*: (\d+)", line)
                if m:
                    model["footer"]["total"] = (i, int(m.group(1)))
                m = re.match(r"^\*\*Paywalled Papers\*\*: (\d+)", line)
                if m:
                    model["footer"]["paywalled"] = (i, int(m.group(1)))
                m = re.match(r"^\*\*Open Access\*\*: ~?(\d+)%", line)
                if m:
                    model["footer"]["open"] = (i, int(m.group(1)))
        return model

    def _parse_glossary(self):
        anchors = set()
        terms = 0
        section = None
        seen = defaultdict(int)
        for line in GLOSSARY.read_text(encoding="utf-8").splitlines():
            if line.startswith("## ") and not line.startswith("###"):
                section = line[3:].strip()
            for level in ("## ", "### ", "#### "):
                if line.startswith(level) and not line.startswith("#" + level):
                    slug = github_slug(line[len(level):].strip())
                    if seen[slug]:
                        anchors.add(f"{slug}-{seen[slug]}")
                    else:
                        anchors.add(slug)
                    seen[slug] += 1
                    break
            if line.startswith("### ") and section not in (
                "Table of Contents", "Cross-References", "Acronyms Quick Reference",
            ):
                terms += 1
        return anchors, terms

    # -- derived data ------------------------------------------------------
    def topic_entries(self):
        for stem, sections in self.topics.items():
            for sec in sections:
                for e in sec["entries"]:
                    yield stem, sec, e

    def topic_urls(self):
        urls = defaultdict(list)  # canon -> [(stem, entry)]
        for stem, sec, e in self.topic_entries():
            urls[canon(e["url"])].append((stem, e))
        return urls

    def counts(self):
        per_area = {stem: sum(len(s["entries"]) for s in secs)
                    for stem, secs in self.topics.items()}
        distinct = len(self.topic_urls())
        policy_docs = sum(
            1 for stem, sec, e in self.topic_entries()
            if stem == "policy" and e["emoji"] == "📄"
        )
        bydate_total = len(self.bydate["bullets"])
        bydate_paywalled = sum(1 for b in self.bydate["bullets"] if b["emoji"] == "🔒")
        return {
            "per_area": per_area,
            "distinct": distinct,
            "policy_docs": policy_docs,
            "areas": len(self.topic_files),
            "glossary_terms": self.glossary_terms,
            "bydate_total": bydate_total,
            "bydate_paywalled": bydate_paywalled,
        }


def rel(path):
    return str(Path(path).resolve().relative_to(ROOT))


def canon(url):
    m = ARXIV_RE.match(url)
    if m:
        return f"arxiv:{m.group(1)}"
    url = url.replace("http://", "https://")
    return url.rstrip("/")


def github_slug(heading):
    # GitHub's anchor algorithm: lowercase, drop everything that is not a word
    # character, space, or hyphen, then spaces -> hyphens. Emoji vanish but
    # their trailing space survives, producing a leading hyphen.
    text = heading.lower()
    text = re.sub(r"[^\w\s-]", "", text)
    return text.replace(" ", "-")


