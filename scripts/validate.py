def self_heal_hookspath(quiet):
    """Per-clone git state is unavoidable; converge it from the repo itself."""
    if not (ROOT / "githooks" / "pre-commit").exists():
        return
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "config", "core.hooksPath"],
            capture_output=True, text=True, timeout=10,
        )
        if out.stdout.strip() != "githooks":
            subprocess.run(
                ["git", "-C", str(ROOT), "config", "core.hooksPath", "githooks"],
                capture_output=True, text=True, timeout=10,
            )
            if not quiet:
                print("note: set git core.hooksPath=githooks (pre-commit validation enabled)")
    except Exception:
        pass


def run_checks():
    repo = Repo()
    check_cross_index(repo)
    check_duplicates(repo)
    check_anchors(repo)
    check_order(repo)
    check_entry_format(repo)
    check_bydate_format(repo)
    check_emoji(repo)
    check_attribution(repo)
    check_counts(repo)
    check_coverage(repo)
    repo.findings.sort(key=lambda f: (f.file, f.line, f.check))
    return repo


def report(repo, stream=sys.stdout):
    errors = sum(1 for f in repo.findings if f.severity == "ERROR")
    warns = len(repo.findings) - errors
    for f in repo.findings:
        print(f.render(), file=stream)
    files = len({f.file for f in repo.findings})
    print(f"validate: {errors} errors, {warns} warnings in {files} files", file=stream)
    return errors


def run_fix():
    fix_numbering()
    repo = Repo()
    fix_missing_bydate(repo)
    fix_order()
    repo = Repo()
    fix_backlinks(repo)
    repo = Repo()
    fix_counts(repo)
    repo = Repo()
    fix_coverage(repo)
    return run_checks()


RELEVANT = ("README.md", "by-date.md", "learning-path.md", "CONTRIBUTING.md")


def run_hook(mode):
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0
    try:
        if mode == "stop" and payload.get("stop_hook_active"):
            return 0
        if mode == "post-tool-use":
            file_path = str((payload.get("tool_input") or {}).get("file_path", ""))
            name = Path(file_path).name
            in_learning = "/learning/" in file_path and file_path.endswith(".md")
            if not (name in RELEVANT or in_learning):
                return 0
        self_heal_hookspath(quiet=True)
        repo = run_checks()
        errors = [f for f in repo.findings if f.severity == "ERROR"]
        if errors:
            # digest for the agent: capped, errors only — full list via manual run
            for f in errors[:25]:
                print(f.render(), file=sys.stderr)
            if len(errors) > 25:
                print(f"... and {len(errors) - 25} more errors "
                      "(run: python3 scripts/validate.py)", file=sys.stderr)
            print(
                f"validate: {len(errors)} errors. Each line ends with a fix hint; "
                "mechanical issues: run `python3 scripts/validate.py --fix`.",
                file=sys.stderr,
            )
            return 2
        return 0
    except Exception:
        return 0  # fail open: a validator bug must never brick editing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fix", action="store_true", help="apply mechanical fixes")
    parser.add_argument("--hook", choices=["post-tool-use", "stop"], help="Claude Code hook mode")
    parser.add_argument("--links", action="store_true", help="check external links (network)")
    args = parser.parse_args()

    if args.hook:
        sys.exit(run_hook(args.hook))
    try:
        self_heal_hookspath(quiet=False)
        if args.links:
            sys.exit(run_links())
        repo = run_fix() if args.fix else run_checks()
        errors = report(repo)
        sys.exit(1 if errors else 0)
    except KeyboardInterrupt:
        sys.exit(3)
    except Exception as exc:  # noqa: BLE001
        print(f"validate: internal error: {exc!r}", file=sys.stderr)
        sys.exit(3)


if __name__ == "__main__":
    main()
