#!/usr/bin/env python3
"""Repo invariant validator for the papers collection.

The repo is the source of truth: this script is stateless and derives
everything from the working tree on each run. It is the single check logic
behind three trigger points:

  * the git pre-commit hook (githooks/pre-commit)  — fail closed
  * Claude Code hooks (.claude/settings.json)      — fail open, feeds agents
  * manual runs                                    — report / --fix / --links

Usage:
  python3 scripts/validate.py                 report all findings
  python3 scripts/validate.py --fix           apply mechanical fixes, then report
  python3 scripts/validate.py --hook post-tool-use   (stdin: Claude hook JSON)
  python3 scripts/validate.py --hook stop            (stdin: Claude hook JSON)
  python3 scripts/validate.py --links         on-demand external link check

Exit codes: 0 clean (warnings allowed), 1 errors, 3 internal error.
Hook modes: 0 clean/irrelevant, 2 errors (stderr shown to the agent).
"""

