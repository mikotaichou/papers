def run_links():
    import urllib.request
    from concurrent.futures import ThreadPoolExecutor
    from urllib.parse import urlparse

    targets = {}  # url -> (file, line)
    for path in [README, LEARNING_PATH, BYDATE, ROOT / "CONTRIBUTING.md",
                 *sorted(LEARNING.glob("*.md"))]:
        if not path.exists():
            continue
        for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for m in MD_LINK_RE.finditer(line):
                url = m.group(2)
                if url.startswith(("http://", "https://")):
                    targets.setdefault(url, (rel(path), i))

    def check(url):
        host = urlparse(url).netloc
        if host in LINK_SKIP_HOSTS:
            return url, None
        req = urllib.request.Request(
            url, method="HEAD",
            headers={"User-Agent": "papers-repo-validator/1.0 (link check)"})
        for method in ("HEAD", "GET"):
            req = urllib.request.Request(
                url, method=method,
                headers={"User-Agent": "papers-repo-validator/1.0 (link check)"})
            try:
                with urllib.request.urlopen(req, timeout=20) as resp:
                    return url, None if resp.status in LINK_OK_CODES or resp.status < 400 else resp.status
            except Exception as exc:  # noqa: BLE001 - report every failure kind
                code = getattr(exc, "code", None)
                if code in LINK_OK_CODES:
                    return url, None
                last = code if code is not None else exc.__class__.__name__
        return url, last

    failures = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        for url, status in pool.map(check, sorted(targets)):
            if status is not None:
                file, line = targets[url]
                failures.append(f"ERROR {file}:{line} [link] {url} -> {status}")
    skipped = sum(1 for u in targets if urlparse(u).netloc in LINK_SKIP_HOSTS)
    for f in failures:
        print(f)
    print(f"links: {len(failures)} failures, {len(targets)} checked, {skipped} skipped (paywalled hosts)")
    return 1 if failures else 0


