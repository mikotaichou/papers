def fix_numbering():
    for path in sorted(LEARNING.glob("*.md")):
        if path.name == "glossary.md":
            continue
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        counter = 0
        changed = False
        for i, line in enumerate(lines):
            if line.startswith("## "):
                counter = 0
            m = ENTRY_RE.match(line.rstrip("\n"))
            if m:
                counter += 1
                if int(m.group(1)) != counter:
                    lines[i] = re.sub(r"^\d+\.", f"{counter}.", line, count=1)
                    changed = True
        if changed:
            path.write_text("".join(lines), encoding="utf-8")


def fix_missing_bydate(repo):
    """Insert topic entries that are absent from by-date.md under their year."""
    bydate_urls = {canon(b["url"]) for b in repo.bydate["bullets"]}
    missing = []
    for stem, sec, e in repo.topic_entries():
        cu = canon(e["url"])
        if cu in bydate_urls:
            continue
        bydate_urls.add(cu)
        years = re.findall(r"(\d{4})", e["rest"])
        if not years:
            continue  # no parseable year: left for the cross-index error
        emoji = f'{e["emoji"]} ' if e["emoji"] else ""
        suffix = " - *Paywalled*" if e["emoji"] == "🔒" else ""
        attr = e["rest"].strip()
        bullet = f'- {emoji}[{e["title"]}]({e["url"]}) {attr}{suffix}'.rstrip()
        missing.append((int(years[-1]), bullet))
    if not missing:
        return
    lines = BYDATE.read_text(encoding="utf-8").splitlines()
    for year, bullet in missing:
        if not any(re.match(rf"^## {year}$", l) for l in lines):
            # create the year section in descending position
            for i, line in enumerate(lines):
                m = re.match(r"^## (\d{4})$", line)
                if m and int(m.group(1)) < year:
                    lines[i:i] = [f"## {year}", "", bullet, ""]
                    break
            else:
                # older than everything: before the footer separator, else at end
                end = next((i for i in range(len(lines) - 1, -1, -1)
                            if lines[i].strip() == "---"), len(lines))
                lines[end:end] = [f"## {year}", "", bullet, ""]
            continue
        year_idx = None
        for i, line in enumerate(lines):
            if re.match(rf"^## {year}$", line):
                year_idx = i
            elif year_idx is not None and (line.startswith("## ") or line.strip() == "---"):
                insert_at = i
                while insert_at > year_idx and lines[insert_at - 1].strip() == "":
                    insert_at -= 1
                lines.insert(insert_at, bullet)
                break
        else:
            if year_idx is not None:  # year is the last section
                lines.append(bullet)
    BYDATE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fix_order():
    """Reorder standard ## YYYY sections (desc) and ### YYYY.MM blocks within them."""
    text = BYDATE.read_text(encoding="utf-8")
    lines = text.splitlines()
    # split: preamble, [(heading, block_lines)], footer(from final ---)
    first = next((i for i, l in enumerate(lines) if re.match(r"^## ", l)), None)
    if first is None:
        return
    footer_start = len(lines)
    for i in range(len(lines) - 1, first, -1):
        if lines[i].strip() == "---":
            footer_start = i
            break
    pre, body, post = lines[:first], lines[first:footer_start], lines[footer_start:]
    sections = []  # (year_or_None, [lines])
    cur = None
    for line in body:
        if line.startswith("## ") and not line.startswith("###"):
            m = re.match(r"^## (\d{4})$", line)
            cur = {"year": int(m.group(1)) if m else None, "lines": [line]}
            sections.append(cur)
        elif cur is not None:
            cur["lines"].append(line)
    if any(s["year"] is None for s in sections):
        return  # non-standard year headings present; fix those first
    # inside each year, reorder month blocks
    for s in sections:
        head, rest = s["lines"][0], s["lines"][1:]
        blocks, loose, curb = [], [], None
        for line in rest:
            if line.startswith("### "):
                m = re.match(r"^### (\d{4})\.(\d{2})$", line)
                curb = {"key": (int(m.group(1)), int(m.group(2))) if m else None,
                        "lines": [line]}
                blocks.append(curb)
            elif curb is None:
                loose.append(line)
            else:
                curb["lines"].append(line)
        if any(b["key"] is None for b in blocks):
            continue
        blocks.sort(key=lambda b: b["key"], reverse=True)
        out = [head]
        loose_stripped = [l for l in loose if l.strip()]
        if loose_stripped and not blocks:
            out.extend(loose)
        else:
            out.append("")
            for l in loose_stripped:
                out.append(l)
            if loose_stripped:
                out.append("")
            for b in blocks:
                block = [l for l in b["lines"]]
                while block and block[-1].strip() == "":
                    block.pop()
                out.extend(block)
                out.append("")
        while out and out[-1].strip() == "":
            out.pop()
        s["lines"] = out
    sections.sort(key=lambda s: s["year"], reverse=True)
    new_body = []
    for s in sections:
        new_body.extend(s["lines"])
        new_body.append("")
    result = pre + new_body + post
    BYDATE.write_text("\n".join(result).rstrip("\n") + "\n", encoding="utf-8")


def fix_backlinks(repo):
    topic_urls = repo.topic_urls()
    lines = BYDATE.read_text(encoding="utf-8").splitlines()
    changed = False
    for b in repo.bydate["bullets"]:
        if b["area_target"] is not None:
            continue
        cu = canon(b["url"])
        owners = topic_urls.get(cu)
        if not owners:
            continue
        stem = owners[0][0]
        label = AREA_LABEL.get(stem, stem.replace("-", " ").title())
        idx = b["line"] - 1
        lines[idx] = f"{lines[idx].rstrip()} — [{label}](learning/{stem}.md)"
        changed = True
    if changed:
        BYDATE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fix_counts(repo):
    c = repo.counts()
    text = README.read_text(encoding="utf-8")
    text = re.sub(r"badge/papers-\d+-blue", f'badge/papers-{c["distinct"]}-blue', text)
    text = re.sub(r"badge/learning-\d+_areas", f'badge/learning-{c["areas"]}_areas', text)
    text = re.sub(r"badge/glossary-\d+_terms", f'badge/glossary-{c["glossary_terms"]}_terms', text)
    text = re.sub(r"\*\*\d+ carefully selected", f'**{c["distinct"]} carefully selected', text)
    text = re.sub(
        r"^\*\*Total\*\*: \d+ papers across \d+ areas \(including \d+ policy[^)]*\)",
        f'**Total**: {c["distinct"]} papers across {c["areas"]} areas '
        f'(including {c["policy_docs"]} policy documents & frameworks)',
        text, flags=re.M,
    )
    text = re.sub(r"\b\d+ terms\b", f'{c["glossary_terms"]} terms', text)

    def table_row(m):
        stem = m.group("stem")
        if stem in c["per_area"]:
            return f'{m.group("pre")}{c["per_area"][stem]}{m.group("post")}'
        return m.group(0)

    text = re.sub(
        r"(?P<pre>^\| \*\*\[[^\]]+\]\(learning/(?P<stem>[a-z-]+)\.md\)\*\* \| [^|]+ \| )\d+(?P<post> \|)",
        table_row, text, flags=re.M,
    )
    README.write_text(text, encoding="utf-8")

    lines = BYDATE.read_text(encoding="utf-8").splitlines()
    open_pct = round(100 * (1 - c["bydate_paywalled"] / c["bydate_total"])) if c["bydate_total"] else 100
    for i, line in enumerate(lines):
        if line.startswith("**Total Papers in Learning Path**:"):
            lines[i] = f'**Total Papers in Learning Path**: {c["bydate_total"]} papers'
        elif line.startswith("**Paywalled Papers**:"):
            lines[i] = f'**Paywalled Papers**: {c["bydate_paywalled"]} (marked with 🔒)'
        elif line.startswith("**Open Access**:"):
            lines[i] = f"**Open Access**: ~{open_pct}%"
    BYDATE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fix_coverage(repo):
    lines = README.read_text(encoding="utf-8").splitlines()
    generated = generate_coverage(repo)
    if COVERAGE_START in lines and COVERAGE_END in lines:
        start, end = lines.index(COVERAGE_START), lines.index(COVERAGE_END)
        lines[start + 1:end] = generated
    else:
        head = next((i for i, l in enumerate(lines) if l.startswith("## ") and "Coverage by Topic" in l), None)
        if head is None:
            return
        end = next((i for i in range(head + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
        # keep the trailing separator that belongs to the next section
        sep = end
        while sep > head + 1 and lines[sep - 1].strip() in ("", "---"):
            sep -= 1
        block = ["", COVERAGE_START, *generated, COVERAGE_END, "", "---", ""]
        lines[head + 1:end] = block
    README.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")


